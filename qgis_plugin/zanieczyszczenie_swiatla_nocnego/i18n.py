def tr(key, lang='pl', **kw):
    pair = S.get(key)
    if pair is None:
        return key
    text = pair[0] if lang == 'pl' else pair[1]
    if kw:
        try:
            return text.format(**kw)
        except (KeyError, IndexError):
            return text
    return text
